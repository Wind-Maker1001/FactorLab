@pytest.mark.parametrize('case', ['outside','invalid_held','zero_exit','deadband','cap_sell','cap_buy'])
def test_intent_edges(oracle,case):
    close,volume=history();day=close.index[-1];previous=close.index[-2]
    holdings={s:0. for s in TICKERS};cash=100000.
    desired=pd.Series(0.,index=TICKERS)
    if case=='outside': holdings['MSFT']=1.
    if case=='invalid_held':
        holdings['AAPL']=1.; volume.loc[previous,'AAPL']=np.nan
    if case=='zero_exit': holdings['AAPL']=.1
    if case=='deadband': desired['AAPL']=.0049
    if case=='cap_buy': desired['AAPL']=.04;volume.loc[previous,'AAPL']=1.
    if case=='cap_sell': holdings['AAPL']=100.;volume.loc[previous,'AAPL']=1.
    old,new=oracle(close,volume),V69Planner(close,volume)
    for obj in (old,new):
        obj.targets=lambda *args:desired.copy()
        obj.trade_calendar=SimpleNamespace(get_step_time=lambda:(day,day))
        obj.trade_position=SimpleNamespace(get_stock_amount_dict=lambda:holdings,get_cash=lambda:cash)
    if case in {'outside','invalid_held'}:
        for obj in (old,new):
            with pytest.raises(ValueError): obj.generate_trade_decision()
    else:
        a,b=old.generate_trade_decision(),new.generate_trade_decision()
        assert a.order_list==b.order_list
        if case=='deadband': assert not b.order_list
        if case=='zero_exit': assert b.order_list[0].amount==.1
        if case.startswith('cap_'): assert b.order_list[0].amount==.001


def test_preopen_wrapper_restart_and_no_open_dependency():
    from factorlab.cross_market.calendar import SessionCalendar
    from factorlab.strategies.v69 import V69Strategy
    close,volume=history();day=close.index[-1]
    while day.weekday()!=0:
        close=close.iloc[:-1];volume=volume.iloc[:-1];day=close.index[-1]
    idx=close.index
    schedule=pd.DataFrame({'open':pd.to_datetime(idx,utc=True)+pd.Timedelta(hours=14,minutes=30),
                           'close':pd.to_datetime(idx,utc=True)+pd.Timedelta(hours=21)},index=idx)
    calendar=SessionCalendar(schedule,'US','America/New_York','synthetic')
    event=dict(session=day,calendar=calendar,close=close.iloc[:-1],volume=volume.iloc[:-1],holdings={},cash=100000.)
    a=V69Strategy().decide(event,{})
    assert len(a['weights'])==8
    assert V69Strategy().decide(event,{})==a
    assert V69Strategy().decide(event,json.loads(json.dumps(a['state'])))['orders']==[]
    future=dict(event,close=close)
    with pytest.raises(ValueError): V69Strategy().decide(future,{})


