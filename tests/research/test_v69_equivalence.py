@pytest.fixture
def oracle(monkeypatch):
    for name in ['qlib', 'qlib.backtest', 'qlib.backtest.decision', 'qlib.strategy', 'qlib.strategy.base']:
        monkeypatch.setitem(sys.modules, name, ModuleType(name))
    sys.modules['qlib.backtest'].backtest = lambda: None
    sys.modules['qlib.backtest.decision'].Order = Order
    sys.modules['qlib.backtest.decision'].TradeDecisionWO = TradeDecisionWO
    sys.modules['qlib.strategy.base'].BaseStrategy = type('BaseStrategy', (), {})
    monkeypatch.syspath_prepend(str(ROOT))
    names = ['v48_strategy','v50','v50.strategy','risk_research','risk_research.parent','v51','v51.strategy','v61','v61.strategy','v69','v69.strategy']
    saved = {n: sys.modules.pop(n) for n in names if n in sys.modules}
    yield importlib.import_module('v69.strategy').Strategy
    for n in names:
        sys.modules.pop(n, None)
    sys.modules.update(saved)


def history():
    rng = np.random.default_rng(69)
    idx = pd.bdate_range('2024-09-02', periods=280)
    close = pd.DataFrame(100*np.exp(np.cumsum(rng.normal(.0005,.018,(280,8)),axis=0)), index=idx, columns=TICKERS)
    close.loc[idx[:125], 'SNDK'] = np.nan
    close.loc[idx[150], 'BA'] = np.nan
    volume = pd.DataFrame(100000.,index=idx,columns=TICKERS)
    return close, volume


def test_all_source_hashes():
    manifest = json.loads((ROOT/'source-manifest.json').read_text())
    for name, meta in manifest['files'].items():
        b = (ROOT/name).read_bytes()
        assert len(b) == meta['bytes']
        assert hashlib.sha256(b).hexdigest() == meta['sha256']


@pytest.mark.parametrize('omit', [False, True])
def test_signal_differential(oracle, omit, tmp_path):
    close, volume = history()
    old, new = oracle(close,volume,omit_sndk=omit), NativeV69(close,volume,omit_sndk=omit)
    for key in ['ma28','ma63','qqq_ma63','vol','breadth','high','confirmed']:
        a,b = getattr(old,key),getattr(new,key)
        if isinstance(a,pd.Series): pd.testing.assert_series_equal(a,b)
        else: pd.testing.assert_frame_equal(a,b)
    rows=[]
    for day in close.index:
        prices=close.loc[day];valid=np.isfinite(prices)&prices.gt(0)
        for held in [pd.Series(0.,index=TICKERS),pd.Series(10.,index=TICKERS),pd.Series([0,1,0,2,0,3,0,4],index=TICKERS,dtype=float)]:
            a=old.targets(day,prices,valid,held);b=new.targets(day,prices,valid,held)
            pd.testing.assert_series_equal(a,b)
            rows.extend((str(day.date()),'omit='+str(omit),str(tuple(held)),s,a[s],b[s],b[s]-a[s]) for s in TICKERS)
    # Durable evidence is generated by the explicit validation command, not tests.
    with (tmp_path/'weights.csv').open('w',newline='') as f: csv.writer(f).writerows(rows)


@pytest.mark.parametrize('cash', [100000.,300000.])
def test_order_differential(oracle,cash):
    close,volume=history()
    old,new=oracle(close,volume),V69Planner(close,volume)
    for i,day in enumerate(close.index[1:],1):
        holdings = {s: float((i+j)%7) for j,s in enumerate(TICKERS)}
        if i <= 126: holdings['SNDK']=0.
        if i==151: holdings['BA']=0.
        pos=SimpleNamespace(get_stock_amount_dict=lambda:holdings,get_cash=lambda:cash)
        for obj in [old,new]:
            obj.trade_position=pos
            obj.trade_calendar=SimpleNamespace(get_step_time=lambda:(day,day))
        a,b=old.generate_trade_decision(),new.generate_trade_decision()
        assert a.order_list==b.order_list
        assert old.last_week==new.last_week
        assert old.decisions==new.decisions


